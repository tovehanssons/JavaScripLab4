"use strict";

function calculateArea(width, height) {
    const area = width * height;
    return area;
}

console.log("Arean är " + calculateArea(4, 5));
console.log("Arean är " + calculateArea(6, 7));
console.log("Arean är " + calculateArea(10, 10));